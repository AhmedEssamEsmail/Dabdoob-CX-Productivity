/**
 * merge-app-css.mjs — emits src/app/legacy-apps.css = every CSS rule that
 * exists in a legacy app bundle but is NOT in productivity's sheet (the base
 * already living in globals.css). Each rule is scoped to that app's routes
 * via [data-app="<app>"] (set on the AppShell root) so app-specific shell
 * overrides — e.g. hub's .nav-link — can't leak onto other modules.
 *
 *   node scripts/legacy/merge-app-css.mjs
 *
 * Scoping rules:
 *   :root                → [data-app="X"]            (vars inherit downward)
 *   :root[attrs]         → html[attrs] [data-app="X"]
 *   html/body top-level  → dropped (reported; none expected — shell mounts #root)
 *   .sel, .sel2 …        → [data-app="X"] .sel, [data-app="X"] .sel2
 *   @media/@supports     → scoped recursively inside
 *   @keyframes/@font-face→ emitted unscoped, deduped by name
 * Extras dedupe globally on (scope,selector,body); identical shared rules skip.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const EXTRACT = path.join(ROOT, '.devin/work/extract')
const BASE_APP = 'productivity'
const APPS = ['hub', 'quality', 'queue', 'people', 'operations', 'desk', 'fcr'].filter(a => a !== BASE_APP)
const OUT_CSS = path.join(ROOT, 'src/app/legacy-apps.css')

const norm = s => s.replace(/\s+/g, ' ').trim()
const stripComments = s => s.replace(/\/\*[\s\S]*?\*\//g, '')

function parseRules(css) {
  css = stripComments(css)
  const rules = []
  let i = 0
  while (i < css.length) {
    while (i < css.length && /\s/.test(css[i])) i++
    if (i >= css.length) break
    let d = 0, j = i
    while (j < css.length && !(css[j] === '{' && d === 0)) {
      if (css[j] === '{') d++
      else if (css[j] === '}') d--
      j++
    }
    const prelude = css.slice(i, j).trim()
    if (j >= css.length) break
    d = 1
    let k = j + 1
    while (k < css.length && d > 0) {
      if (css[k] === '{') d++
      else if (css[k] === '}') d--
      k++
    }
    const body = css.slice(j + 1, k - 1)
    if (prelude.startsWith('@media') || prelude.startsWith('@supports')) {
      rules.push(...parseRules(body).map(r => ({ ...r, at: r.at ? `${prelude}>${r.at}` : prelude })))
    } else if (prelude.startsWith('@')) {
      rules.push({ sel: norm(prelude), body: norm(body), at: null, atRule: true })
    } else {
      rules.push({ sel: norm(prelude), body: norm(body), at: null })
    }
    i = k
  }
  return rules
}

const keyOf = r => `${r.at || ''}|${r.atRule ? '@' : ''}${r.sel}`

function scopeSelector(sel, app) {
  const scope = `[data-app="${app}"]`
  return sel.split(',').map(part => {
    part = part.trim()
    if (part === ':root') return scope
    if (part === 'html' || part === 'body') return null // dropped, reported
    if (part.startsWith(':root')) {
      const rest = part.slice(5) // e.g. [data-theme=dark] or :not(...)
      return `html${rest} ${scope}`
    }
    if (part.startsWith('html ')) return `html ${scope} ${part.slice(5)}`
    if (part.startsWith('body ')) return `body ${scope} ${part.slice(5)}`
    return `${scope} ${part}`
  }).filter(Boolean).join(', ')
}

const baseRules = parseRules(fs.readFileSync(path.join(EXTRACT, BASE_APP, 'app.css'), 'utf8'))
const baseMap = new Map(baseRules.map(r => [keyOf(r), r.body]))

const emitted = new Map() // key|body -> app (global dedupe incl scoped sel)
const dropped = []
const sections = []

for (const app of APPS) {
  const f = path.join(EXTRACT, app, 'app.css')
  if (!fs.existsSync(f)) continue
  const mine = []
  for (const r of parseRules(fs.readFileSync(f, 'utf8'))) {
    const k = keyOf(r)
    if (baseMap.get(k) === r.body) continue // identical shared rule
    if (!r.atRule) {
      const scoped = scopeSelector(r.sel, app)
      if (!scoped) { dropped.push(`${app}: ${r.sel}`); continue }
      r.sel = scoped
    }
    const emitKey = `${app}|${k}|${r.body}`
    if (emitted.has(emitKey)) continue
    emitted.set(emitKey, app)
    mine.push(r)
  }
  if (mine.length) sections.push({ app, rules: mine })
}

let out = `/* generated by scripts/legacy/merge-app-css.mjs — app-specific rules absent from
   globals.css (productivity sheet), scoped under [data-app] on the shell root.
   Do not hand-edit; re-run the script. */\n`
if (dropped.length) out += `/* dropped unscoped html/body rules: ${dropped.join(' | ')} */\n`
for (const { app, rules } of sections) {
  out += `\n/* ============ ${app} ============ */\n`
  let curAt = null
  for (const r of rules) {
    if (r.at !== curAt) {
      if (curAt) out += '}\n'
      if (r.at) out += `${r.at} {\n`
      curAt = r.at
    }
    out += (r.at ? '  ' : '') + `${r.sel} { ${r.body} }\n`
  }
  if (curAt) out += '}\n'
}

fs.writeFileSync(OUT_CSS, out)
console.log('rules per app:', JSON.stringify(Object.fromEntries(sections.map(s => [s.app, s.rules.length]))))
console.log('dropped:', dropped.length, dropped.slice(0, 10))
console.log('wrote', OUT_CSS, out.length, 'bytes')
